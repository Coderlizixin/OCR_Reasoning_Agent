"""
OCR-Agent V4 Pseudo-Plan: Uses pre-built planning pseudo-labels (from reasoning GT)
====================================================================================
Extends OCRAgentV4 but replaces Stage 1 (Planning) with pre-built plans loaded
from JSON files. The pseudo-labels were generated by convert_gt_to_planning.py,
which converts human reasoning ground-truth traces into V4 planning JSON format.

All other stages (Executor, Reasoning) are inherited unchanged from OCRAgentV4.

Key difference from OCRAgentV4:
  - Stage 1 (Planning):  NO API call — looks up pre-built plan by dataset index
                          (parsed from image filename) or question text.
  - Stage 2 (Executor):   Same as V4 — executes steps topologically with retry
  - Stage 3 (Reasoning):  Same as V4 — text-only synthesis of step results

This allows testing: given a PERFECT plan (from human GT), how well does the
executor + reasoning pipeline perform?
"""
import os
import re
import json
from vlmeval.vlm.ocr_agent_v4 import OCRAgentV4
from vlmeval.api.gpt import _log_diag


class OCRAgentV4PseudoPlan(OCRAgentV4):
    """V4 OCR Agent with pseudo-label planning instead of model-generated plans.

    Instead of calling the model to generate a plan (Stage 1), this agent looks up
    a pre-built plan from planning pseudo-labels. Matching is done by:

    1. **Index** (primary): The dataset index is parsed from the image filename
       (format: {img_root}/{index}.jpg, as written by ImageBaseDataset.dump_image).
    2. **Question text** (fallback): For isolated testing where images are not
       named by dataset index.

    All other stages (Executor, Reasoning) are identical to OCRAgentV4.
    """

    def __init__(self, pseudo_plan_dir='test_case/planning_pseudo_labels', **kwargs):
        """Initialize with pseudo-plan directory.

        Args:
            pseudo_plan_dir: Directory containing pseudo-label JSON files.
                             Each file should have: {"index": N, "question": "...",
                             "plan": {"steps": [...]}, ...}
            **kwargs: All other arguments passed to OCRAgentV4.
        """
        super().__init__(**kwargs)
        self.pseudo_plan_dir = pseudo_plan_dir
        self._pseudo_plans_by_idx = {}   # dataset_index (int) -> plan steps
        self._pseudo_plans_by_q = {}     # question_text -> plan steps
        self._pseudo_plan_meta = {}      # question_text or "idx:N" -> meta dict
        self._load_pseudo_labels()

    # ------------------------------------------------------------------
    # Pseudo-label loading
    # ------------------------------------------------------------------

    def _load_pseudo_labels(self):
        """Load all pseudo-label JSON files and build index+question->plan maps."""
        if not os.path.isdir(self.pseudo_plan_dir):
            _log_diag(
                f'[V4-PseudoPlan] WARNING: pseudo_plan_dir not found: '
                f'{self.pseudo_plan_dir}'
            )
            return

        json_files = sorted([
            f for f in os.listdir(self.pseudo_plan_dir) if f.endswith('.json')
        ])
        loaded_by_idx = 0
        loaded_by_q = 0
        dupes = 0

        for fname in json_files:
            fpath = os.path.join(self.pseudo_plan_dir, fname)
            try:
                with open(fpath, 'r', encoding='utf-8') as f:
                    data = json.load(f)
            except (json.JSONDecodeError, IOError) as e:
                _log_diag(f'[V4-PseudoPlan] Failed to load {fname}: {e}')
                continue

            question = data.get('question', '').strip()
            plan = data.get('plan', {})
            steps = plan.get('steps', [])
            idx = data.get('index')

            if not question or not steps:
                continue

            meta = {
                'index': idx,
                'gt_final_answer': data.get('gt_final_answer', ''),
                'gt_steps_count': data.get('gt_steps_count', 0),
            }

            # Index-based (primary key for batch evaluation)
            if idx is not None:
                self._pseudo_plans_by_idx[idx] = steps
                self._pseudo_plan_meta[f'idx:{idx}'] = meta
                loaded_by_idx += 1

            # Question-based (fallback for individual testing)
            if question not in self._pseudo_plans_by_q:
                self._pseudo_plans_by_q[question] = steps
                self._pseudo_plan_meta[question] = meta
                loaded_by_q += 1
            else:
                dupes += 1

        _log_diag(
            f'[V4-PseudoPlan] Loaded {loaded_by_idx} plans by index, '
            f'{loaded_by_q} unique questions (skipped {dupes} duplicates) '
            f'from {self.pseudo_plan_dir}'
        )

    # ------------------------------------------------------------------
    # Stage 1: Planning (pseudo-label lookup — NO API call)
    # ------------------------------------------------------------------

    # Regex to extract dataset index from image path: ".../123.jpg" or ".../123.png"
    _IMG_INDEX_RE = re.compile(r'[/\\](\d+)\.(?:jpg|jpeg|png|bmp|webp)$', re.IGNORECASE)

    @classmethod
    def _parse_index_from_path(cls, image_path):
        """Extract dataset index from image filename, e.g. '.../21.jpg' -> 21."""
        if not image_path:
            return None
        m = cls._IMG_INDEX_RE.search(image_path)
        return int(m.group(1)) if m else None

    def _planning(self, image_path, question):
        """Look up pre-built plan by dataset index (primary) or question text (fallback).

        Args:
            image_path: Path to the image. Used to extract dataset index
                        (format: {img_root}/{index}.jpg).
            question: The full question text from the dataset.

        Returns:
            (steps: list | None, status: str, plan_text: str)
        """
        clean_q = question.strip()

        # ---- Strategy 1 (PRIMARY): Extract index from image path ----
        idx = self._parse_index_from_path(image_path)
        if idx is not None and idx in self._pseudo_plans_by_idx:
            steps = self._pseudo_plans_by_idx[idx]
            meta = self._pseudo_plan_meta.get(f'idx:{idx}', {})
            _log_diag(
                f'[V4-PseudoPlan] Index match idx={idx}: {len(steps)} steps'
            )
            plan_text = json.dumps({'steps': steps}, ensure_ascii=False)
            return steps, 'success', plan_text

        if idx is not None:
            _log_diag(
                f'[V4-PseudoPlan] Index {idx} parsed from path but no pseudo-plan found. '
                f'Falling back to question matching.'
            )

        # ---- Strategy 2: Exact question match ----
        if clean_q in self._pseudo_plans_by_q:
            steps = self._pseudo_plans_by_q[clean_q]
            meta = self._pseudo_plan_meta.get(clean_q, {})
            _log_diag(
                f'[V4-PseudoPlan] Exact question match idx={meta.get("index")}: '
                f'{len(steps)} steps'
            )
            plan_text = json.dumps({'steps': steps}, ensure_ascii=False)
            return steps, 'success', plan_text

        # ---- ASKStrategy 3: stored_q starts with clean_q (question + suffix) ----
        for stored_q, steps in self._pseudo_plans_by_q.items():
            if clean_q.startswith(stored_q):
                meta = self._pseudo_plan_meta.get(stored_q, {})
                _log_diag(
                    f'[V4-PseudoPlan] Prefix question match idx={meta.get("index")}: '
                    f'{len(steps)} steps'
                )
                plan_text = json.dumps({'steps': steps}, ensure_ascii=False)
                return steps, 'success', plan_text

        # ---- Strategy 4: Fuzzy — one contains the other ----
        for stored_q, steps in self._pseudo_plans_by_q.items():
            if stored_q in clean_q or clean_q in stored_q:
                meta = self._pseudo_plan_meta.get(stored_q, {})
                _log_diag(
                    f'[V4-PseudoPlan] Fuzzy question match idx={meta.get("index")}: '
                    f'{len(steps)} steps'
                )
                plan_text = json.dumps({'steps': steps}, ensure_ascii=False)
                return steps, 'success', plan_text

        # ---- No match ----
        _log_diag(
            f'[V4-PseudoPlan] No pseudo-plan found (idx={idx}). '
            f'Question preview: {clean_q[:150]}'
        )
        return None, self.PLANNING_FAIL_PARSE, ''
